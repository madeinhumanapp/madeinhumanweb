/** Retorna el text traduït per a `idioma` i `clau`, substituint `{nom}` pels `valors` indicats. */
export function t(idioma, clau, valors = {}) {
  const dic = TEXTOS[idioma] || TEXTOS.ca;
  const plantilla = dic[clau];
  if (plantilla === undefined) throw new Error(`Clau de text desconeguda (${idioma}): ${clau}`);
  return String(plantilla).replace(/\{([a-zA-Z0-9_]+)\}/g, (tot, nom) => (
    Object.prototype.hasOwnProperty.call(valors, nom) ? String(valors[nom]) : tot
  ));
}
